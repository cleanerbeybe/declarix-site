// Re-observe every official source behind the CDS Operations Radar.
// Usage: npm run radar:check            -> report changed sources and records due a recheck
//        npm run radar:check -- --write -> also refresh scripts/radar-observations.mjs for UNCHANGED sources
// A changed source is never written automatically: it becomes a candidate for a reviewed record update.
import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { radarObservations } from './radar-observations.mjs'
import { freshnessState, radarRecords } from './radar.mjs'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const write = process.argv.includes('--write')
const now = new Date()
const contentApi = (url) => (url.startsWith('https://www.gov.uk/') ? url.replace('https://www.gov.uk/', 'https://www.gov.uk/api/content/') : url)

const next = structuredClone(radarObservations)
const changed = []
for (const [key, observation] of Object.entries(radarObservations)) {
  const response = await fetch(contentApi(observation.url), { headers: { 'user-agent': 'DeclarixRadar/1.1 (+https://getdeclarix.com/editorial-policy/)' } })
  if (!response.ok) {
    changed.push({ key, reason: `HTTP ${response.status}` })
    continue
  }
  const bytes = Buffer.from(await response.arrayBuffer())
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  if (sha256 === observation.sha256) {
    next[key] = { ...observation, observedAt: now.toISOString().replace(/\.\d{3}Z$/, 'Z') }
    console.log(`unchanged  ${key}`)
  } else {
    let updatedAt = null
    try {
      updatedAt = JSON.parse(bytes.toString('utf8')).public_updated_at || null
    } catch {}
    changed.push({ key, reason: `hash ${observation.sha256.slice(0, 12)} -> ${sha256.slice(0, 12)}${updatedAt ? `; source updated ${updatedAt}` : ''}` })
  }
}

for (const item of changed) console.log(`CHANGED    ${item.key}: ${item.reason}`)
const due = radarRecords.filter((record) => ['stale', 'expired'].includes(freshnessState(record, now)))
for (const record of due) console.log(`RECHECK    ${record.id} (${freshnessState(record, now)})`)

if (write) {
  const header = [
    '// Retained official-source observations for the CDS Operations Radar.',
    '// Generated by fetching each GOV.UK Content API response (or the HMRC Developer Hub page) and hashing the exact bytes.',
    '// Regenerate with `npm run radar:check -- --write` after re-observing; never hand-edit a hash.',
  ]
  await writeFile(join(root, 'scripts/radar-observations.mjs'), `${header.join('\n')}\nexport const radarObservations = ${JSON.stringify(next, null, 2)}\n`)
  console.log(`Refreshed observation times for unchanged sources. ${changed.length} changed source(s) need a reviewed record update.`)
}
process.exitCode = changed.length ? 2 : 0
